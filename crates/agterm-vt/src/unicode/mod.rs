//! table and full case folding, all looked up in tables generated from the UCD.
//!
//! Ghostty: `src/unicode/main.zig` at `LIBGHOSTTY_VT_REV` (the module root; the files below follow the rest of
//! `src/unicode`, and `case_folding` follows uucode's `case_folding_full` field that `src/build/uucode_config.zig`
//! declares). The tables are Ghostty's generator output at `RUSTTY_UNICODE_GHOSTTY_REV` (uucode 0.2.0 @ `9d555245`,
//! UCD 18.0.0); nothing Unicode moved from there to the pin.
//! rustty: `crates/rustty-unicode/src/lib.rs` at `RUSTTY_REV` (MIT), and `rustty-vt`'s root `unicode` re-exports,
//! which are this module itself here.
//! Changes: the tables are checked-in generated sources (see [`generated`]), regenerated by the generator the
//! zig-free-core plan's Task 6 ports, never edited; the lookups are safe Rust (see [`lut`]); a code point is a `u32`
//! masked to Zig's `u21`. `main.zig`'s re-exports (`table`, `Properties`, the grapheme functions) are their modules'
//! paths here, and none is public: the crate's public surface is the embedder layer's. Ghostty's `refAllDecls` test
//! has no counterpart: Rust compiles every item anyway.

