use props_table::table;

/// The terminal display width of a code point in cells: 0, 1 or 2.
///
/// The width table the terminal lays out printed text with: 0 for zero-width code points (controls, combining marks,
/// default ignorables, surrogates), 2 for wide ones (East Asian Wide and Fullwidth, regional indicators, clamped at
/// 2), 1 otherwise.
///
/// It looks at one code point and cannot account for grapheme cluster rules (VS16, combining sequences); a caller
/// that needs cluster widths uses [`grapheme_width`]. Summing per-code-point widths is only right with mode 2027 off.
#[inline]
pub(crate) fn codepoint_width(cp: u32) -> u8 {
    table().get(cp).width
}

#[cfg(test)]
mod tests {
    use super::codepoint_width;

    /// Ghostty's `test "codepointWidth"`.
    #[test]
    fn codepoint_width_table() {
        let cases: [(u32, u8, &str); 19] = [
            // Narrow.
            (u32::from('a'), 1, "'a'"),
            (u32::from(' '), 1, "space"),
            (0x10_FFFF, 1, "the largest code point"),
            // C0 and C1 controls.
            (0x00, 0, "NUL"),
            (0x07, 0, "BEL"),
            (0x1B, 0, "ESC"),
            (0x7F, 0, "DEL"),
            (0x80, 0, "C1 PAD"),
            // Zero-width code points.
            (0x0301, 0, "combining acute"),
            (0x200B, 0, "zero width space"),
            (0x200D, 0, "ZWJ"),
            (0xFE0F, 0, "VS16"),
            (0xD800, 0, "surrogate"),
            // Wide.
            (0x4E00, 2, "CJK ideograph"),
            (0xFF21, 2, "fullwidth A"),
            (0xAC00, 2, "Hangul syllable"),
            (0x1F600, 2, "emoji"),
            (0x1F1E6, 2, "regional indicator"),
            (0x2E3B, 2, "three-em dash, clamped"),
        ];
        for (cp, width, what) in cases {
            assert_eq!(codepoint_width(cp), width, "{what} (U+{cp:04X})");
        }
    }

    /// rustty's Unicode 18 spot checks: `East_Asian_Width=W` ranges new in `DerivedEastAsianWidth-18.0.0`.
    #[test]
    fn codepoint_width_unicode_18_wide_ranges() {
        for cp in [
            0x18E00, 0x19191, // Jurchen
            0x191A0, 0x191D2, // Jurchen Radicals
            0x3D000, 0x3FC3F, // Small Seal
            0x1F6D9, 0x1FA8B, 0x1FA8D, 0x1FACC, 0x1FADD, 0x1FAEB, 0x1FAF9, 0x1FAFA, // E18.0
        ] {
            assert_eq!(2, codepoint_width(cp), "U+{cp:X}");
        }
    }
}
