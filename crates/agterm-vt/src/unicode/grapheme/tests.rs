//! Ghostty's grapheme tests, uucode's `BreakState` and Unicode 18 boundary tests run through the precomputed table.

use super::{
    Base, BreakState, GraphemeWidth, GraphemeWidthEffect, PRECOMPUTE, grapheme_break, grapheme_width,
    grapheme_width_effect,
};
use crate::unicode::generated::grapheme_data;
use crate::unicode::props_table::table;

#[test]
fn grapheme_break_emoji_modifier() {
    // An emoji and a modifier.
    let mut state = BreakState::default();
    assert!(!grapheme_break(0x261D, 0x1F3FF, &mut state));

    // A non-emoji and an emoji modifier.
    let mut state = BreakState::default();
    assert!(grapheme_break(0x22, 0x1F3FF, &mut state));
}

#[test]
fn long_emoji_zwj_sequences() {
    // Family: woman, woman, girl, boy, then '_'.
    let cps: Vec<u32> = "\u{1F469}\u{200D}\u{1F469}\u{200D}\u{1F467}\u{200D}\u{1F466}_"
        .chars()
        .map(u32::from)
        .collect();
    let mut state = BreakState::default();
    for pair in cps[..cps.len() - 1].windows(2) {
        assert!(
            !grapheme_break(pair[0], pair[1], &mut state),
            "{:X} {:X}",
            pair[0],
            pair[1]
        );
    }
    assert!(grapheme_break(0x1F466, u32::from('_'), &mut state));
}

/// uucode's `test "BreakState table index layout"`.
#[test]
fn break_state_table_index_layout() {
    let s = BreakState::new;
    assert_eq!(0, BreakState::default().table_index());
    assert_eq!(1, s(true, Base::Default).table_index());
    assert_eq!(2, s(false, Base::ExtendedPictographic).table_index());
    assert_eq!(3, s(true, Base::ExtendedPictographic).table_index());
    assert_eq!(4, s(false, Base::RegionalIndicator).table_index());
    assert_eq!(5, BreakState::TABLE_LEN);
    assert_eq!(5, s(true, Base::RegionalIndicator).table_index());
    for i in 0..u8::try_from(BreakState::TABLE_LEN).unwrap() {
        let state = BreakState::from_table_index(i);
        assert_eq!(usize::from(i), state.table_index());
        // The field reads round-trip through the stored bit pattern.
        assert_eq!(state, s(state.after_linker(), state.base()));
    }
}

/// The decoded table is the generated bytes, entry for entry, and never hands back a state without a row.
#[test]
fn the_precompute_table_is_the_generated_bytes() {
    for (i, (value, &byte)) in PRECOMPUTE.iter().zip(grapheme_data::DATA.iter()).enumerate() {
        let state = u8::try_from(value.state.table_index()).unwrap();
        assert_eq!(u8::from(value.result) | (state << 1), byte, "entry {i}");
        assert!(value.state.table_index() < BreakState::TABLE_LEN, "entry {i}");
    }
}

/// uucode's `test "Unicode 18 Indic linker boundaries and overlapping emoji sequences"` through Ghostty's
/// precomputed `graphemeBreak`: all non-control code points, so its `isBreakNoControl` column.
#[test]
fn unicode_18_indic_linker_boundaries_and_overlapping_emoji_sequences() {
    let cases: [(&[u32], &[bool]); 19] = [
        // GB9c no longer needs a leading consonant: Linker Extend* x Consonant.
        (&[0x094D, 0x0915], &[false]),
        (&[0x0061, 0x094D, 0x0915], &[false, false]),
        (&[0x094D, 0x0300, 0x200D, 0x0915], &[false, false, false]),
        (&[0x094D, 0x094D, 0x0915], &[false, false]),
        // Extend without a linker doesn't join a consonant.
        (&[0x0915, 0x0300, 0x0915], &[false, true]),
        // A consonant ends the linker sequence.
        (&[0x094D, 0x0915, 0x0300, 0x0915], &[false, false, true]),
        // Only InCB=Extend continues the sequence: ZWNJ, SpacingMark and an emoji modifier all end it.
        (&[0x094D, 0x200C, 0x0300, 0x0915], &[false, false, true]),
        (&[0x094D, 0x0903, 0x0915], &[false, true]),
        (&[0x094D, 0x1F3FB, 0x0915], &[true, true]),
        // InCB=Linker with GCB=Other breaks before it, but still joins a following consonant.
        (&[0x0061, 0x1CF5, 0x0300, 0x0915], &[true, false, false]),
        (&[0x0061, 0x1CF6, 0x0915], &[true, false]),
        (&[0x0061, 0x11A3A, 0x11A0B], &[true, false]),
        (&[0x11A3A, 0x0061], &[true]),
        // GB9c and GB11 overlap: a linker inside an emoji sequence can still lead to a ZWJ emoji or a consonant.
        (
            &[0x1F600, 0x094D, 0x0300, 0x200D, 0x1F600],
            &[false, false, false, false],
        ),
        (&[0x1F600, 0x094D, 0x0300, 0x0915], &[false, false, false]),
        (
            &[0x1F600, 0x094D, 0x200C, 0x200D, 0x1F600],
            &[false, false, false, false],
        ),
        (&[0x1F600, 0x094D, 0x200C, 0x0915], &[false, false, true]),
        // An emoji modifier sequence can lead into GB9c.
        (&[0x1F44D, 0x1F3FB, 0x094D, 0x0915], &[false, false, false]),
        // A GCB=Other linker ends the emoji sequence.
        (&[0x1F600, 0x1CF5, 0x0915], &[true, false]),
    ];
    for (cps, breaks) in cases {
        let mut state = BreakState::default();
        for (i, &expected) in breaks.iter().enumerate() {
            assert_eq!(
                expected,
                grapheme_break(cps[i], cps[i + 1], &mut state),
                "{cps:X?} at {i}"
            );
        }
    }
}

/// Ghostty's `test "grapheme width: variation selectors"`.
#[test]
fn grapheme_width_variation_selectors() {
    assert_eq!(GraphemeWidthEffect::Wide, grapheme_width_effect(0x2764, 0xFE0F));
    assert_eq!(GraphemeWidthEffect::Narrow, grapheme_width_effect(0x23, 0xFE0E));
    assert_eq!(
        GraphemeWidthEffect::Ignore,
        grapheme_width_effect(u32::from('x'), 0xFE0F)
    );

    let x = u32::from('x');
    let cases: [(&[u32], usize, u8); 8] = [
        (&[0x2764, 0xFE0F], 2, 2),
        (&[0x23, 0xFE0F], 2, 2),
        (&[x, 0xFE0F], 2, 1),
        (&[x, 0xFE0F, 0xFE0F], 3, 1),
        (&[0x23, 0xFE0E], 2, 1),
        (&[0x231A, 0xFE0E], 2, 1),
        (&[0x231A, 0xFE0E, 0xFE0F], 3, 1),
        (&[0x1F3F4, 0x200D, 0x2620, 0xFE0F], 4, 2),
    ];
    for (cps, len, width) in cases {
        assert_eq!(GraphemeWidth { len, width }, grapheme_width(cps), "{cps:X?}");
    }
}

/// Ghostty's `test "grapheme width: emoji sequences"`.
#[test]
fn grapheme_width_emoji_sequences() {
    assert_eq!(
        GraphemeWidth { len: 5, width: 2 },
        grapheme_width(&[0x1F468, 0x200D, 0x1F469, 0x200D, 0x1F467])
    );
    assert_eq!(
        GraphemeWidth { len: 3, width: 2 },
        grapheme_width(&[0x23, 0xFE0F, 0x20E3])
    );
    assert_eq!(
        GraphemeWidth { len: 2, width: 1 },
        grapheme_width(&[u32::from('1'), 0x20E3])
    );
    assert_eq!(GraphemeWidth { len: 2, width: 2 }, grapheme_width(&[0x1F44B, 0x1F3FF]));
}

/// Ghostty's `test "grapheme width: spacing marks can widen narrow clusters"`.
#[test]
fn grapheme_width_spacing_marks_widen() {
    let a = u32::from('a');
    let mark = (0..0x11_0000_u32)
        .find(|&cp| {
            let props = table().get(cp);
            props.width == 1 && !props.width_zero_in_grapheme && !grapheme_break(a, cp, &mut BreakState::default())
        })
        .expect("a spacing mark should exist");
    assert_eq!(1, table().get(mark).width);
    assert!(!table().get(mark).width_zero_in_grapheme);
    assert_eq!(GraphemeWidth { len: 2, width: 2 }, grapheme_width(&[a, mark]));
}

/// Ghostty's `test "grapheme width: segmentation"`.
#[test]
fn grapheme_width_segmentation() {
    let (a, b) = (u32::from('a'), u32::from('b'));
    assert_eq!(GraphemeWidth { len: 1, width: 1 }, grapheme_width(&[a]));
    assert_eq!(GraphemeWidth { len: 1, width: 1 }, grapheme_width(&[a, b]));
    assert_eq!(
        GraphemeWidth { len: 2, width: 2 },
        grapheme_width(&[0x1F1E6, 0x1F1E7, 0x1F1E8])
    );
    assert_eq!(GraphemeWidth { len: 1, width: 2 }, grapheme_width(&[0x1F1E8]));
    assert_eq!(GraphemeWidth { len: 0, width: 0 }, grapheme_width(&[]));
    assert_eq!(GraphemeWidth { len: 2, width: 0 }, grapheme_width(&[0x0301, 0x0302]));
}

/// Ghostty's `test "grapheme width: u32 invalid codepoints stand alone"`.
#[test]
fn grapheme_width_u32_invalid() {
    assert_eq!(GraphemeWidth { len: 1, width: 1 }, grapheme_width(&[0x11_0000, 0x0301]));
    assert_eq!(
        GraphemeWidth { len: 1, width: 1 },
        grapheme_width(&[u32::from('a'), 0x11_0000])
    );
}
