use super::source::hexencode;
use super::{SOURCE_FILE, source_file, xtgettcap};
use crate::provenance::LIBGHOSTTY_VT_REV;

/// The checked-in source, as the crate is built with it.
const CHECKED_IN: &str = include_str!("../../terminfo/xterm-ghostty.terminfo");

fn query(name: &str) -> Option<&'static [u8]> {
    xtgettcap(&hexencode(name.as_bytes()))
}

#[test]
fn the_checked_in_source_is_the_entry_encoded() {
    // line endings aside, so a checkout with CRLF endings compares equal; scripts/gen-ghostty-terminfo.sh rewrites it
    assert_eq!(CHECKED_IN.replace("\r\n", "\n"), source_file(LIBGHOSTTY_VT_REV));
    assert_eq!(SOURCE_FILE, "terminfo/xterm-ghostty.terminfo");
}

#[test]
fn the_source_file_names_its_origin_then_holds_the_entry() {
    let file = source_file("0123abcd");
    let mut lines = file.lines();
    assert_eq!(
        lines.next(),
        Some("# xterm-ghostty: Ghostty's terminfo entry (src/terminfo/ghostty.zig at Ghostty 0123abcd).")
    );
    assert!(
        lines
            .next()
            .is_some_and(|l| l.starts_with("# Generated by agterm-vt's gen-terminfo"))
    );
    assert_eq!(lines.next(), Some("xterm-ghostty|ghostty|Ghostty,"));
    assert!(file.ends_with("\tsc=\\E7,\n"));
    // tic reads `#` in the first column as a comment, and nothing else starts with one
    assert_eq!(file.lines().filter(|l| l.starts_with('#')).count(), 2);
}

#[test]
fn xtgettcap_answers_a_known_capability() {
    // a boolean, a number, a string encoded (\E as ESC, ^? as DEL) and one with parameters, as written
    assert_eq!(query("Tc"), Some(b"\x1bP1+r5463\x1b\\".as_slice()));
    assert_eq!(query("colors"), Some(b"\x1bP1+r636F6C6F7273=323536\x1b\\".as_slice()));
    assert_eq!(query("kf1"), Some(b"\x1bP1+r6B6631=1B4F50\x1b\\".as_slice()));
    assert_eq!(query("kbs"), Some(b"\x1bP1+r6B6273=7F\x1b\\".as_slice()));
    assert_eq!(
        query("Smulx"),
        Some(b"\x1bP1+r536D756C78=5C455B343A25703125646D\x1b\\".as_slice())
    );
    // the queryable extras
    assert_eq!(query("Co"), Some(b"\x1bP1+r436F=323536\x1b\\".as_slice()));
    assert_eq!(query("RGB"), Some(b"\x1bP1+r524742=38\x1b\\".as_slice()));
    // TN names Ghostty's entry (the handler answers TN from the embedder's name instead)
    assert_eq!(
        query("TN"),
        Some(b"\x1bP1+r544E=787465726D2D67686F73747479\x1b\\".as_slice())
    );
}

#[test]
fn xtgettcap_leaves_an_unknown_capability_unanswered() {
    assert_eq!(query("zz"), None);
    assert_eq!(query("smulx"), None);
    assert_eq!(xtgettcap(b""), None);
}

#[test]
fn xtgettcap_keys_are_uppercase_hex_names() {
    // `kf1` is 6B 66 31; the DCS handler uppercases a request before the lookup, so only that form is a key
    assert!(xtgettcap(b"6B6631").is_some());
    assert_eq!(xtgettcap(b"6b6631"), None);
    assert_eq!(xtgettcap(b"kf1"), None);
    // a half-encoded name is no name
    assert_eq!(xtgettcap(b"6B663"), None);
    // every answer names the key it was asked for, hex-encoded
    for name in ["am", "cup", "setaf", "kDC7", "fullkbd"] {
        let key = hexencode(name.as_bytes());
        let answer = xtgettcap(&key).unwrap();
        assert!(answer.starts_with(b"\x1bP1+r"));
        assert!(answer[5..].starts_with(&key));
        assert!(answer.ends_with(b"\x1b\\"));
    }
}
