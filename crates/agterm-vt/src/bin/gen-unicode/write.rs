/// `grapheme_data.rs`.
pub(crate) fn grapheme_data(inputs: &Inputs, data: &[u8; 8192]) -> String {
    let mut out = String::new();
    header(
        &mut out,
        &[
            "The precomputed grapheme-break table that `src/unicode/grapheme.zig` builds at comptime from \
             `uucode.grapheme.computeGraphemeBreakNoControl` over every (state, property, property) key. Each entry \
             packs a `Value { result, state }` into its low 4 bits: bit 0 is `result`, bits 1..=3 the `BreakState` \
             table index (`after_linker` in bit 1, `base` in bits 2..=3). Keys whose state is not a table row \
             (`BreakState.table_len` = 5) or whose break property is past the enum's last field are zero."
                .to_owned(),
            format!(
                "Generated by `scripts/gen-vt-unicode.sh`: Ghostty's `Precompute.data` (`src/unicode/grapheme.zig` at \
                 `LIBGHOSTTY_VT_REV`) over the rules of {}, dumped as bytes, which `grapheme` decodes into its values \
                 at compile time. Do not edit: rerun the script.",
                uucode(inputs)
            ),
        ],
    );
    array(&mut out, "pub(crate) const DATA", "u8", &numbers(data));
    out
}

/// `case_folding_data.rs`.
pub(crate) fn case_folding_data(inputs: &Inputs, folds: &[(u32, Vec<u32>)], full_entries: usize) -> String {
    let mut out = String::new();
    header(
        &mut out,
        &[
            format!(
                "Unicode full case folding, uucode's `case_folding_full` field, which the `runtime` table of \
                 `src/build/uucode_config.zig` declares: for each code point with a status-F mapping in \
                 `CaseFolding.txt` that mapping, else its status-C mapping (uucode's `CaseFoldingFull`); code points \
                 with neither are absent and fold to themselves. Statuses S and T are not full folding. {} C entries \
                 and {full_entries} F entries, {} code points.",
                folds.len() - full_entries,
                folds.len()
            ),
            format!(
                "Generated by `scripts/gen-vt-unicode.sh` from the UCD {} that {} ships. Zig reads uucode's own \
                 table; here it is a sorted `(code point, mapping)` list. Do not edit: rerun the script.",
                inputs.ucd_version,
                uucode(inputs)
            ),
        ],
    );
    out.push_str("/// `(code point, mapping)` sorted by code point; unused mapping slots are 0.\n#[rustfmt::skip]\n");
    out.push_str("pub(crate) const CASE_FOLDING_FULL: &[(u32, [u32; 3])] = &[\n");
    for (cp, mapping) in folds {
        let slot = |i: usize| mapping.get(i).copied().unwrap_or(0);
        let _ = writeln!(
            out,
            "    (0x{cp:04X}, [0x{:04X}, 0x{:04X}, 0x{:04X}]),",
            slot(0),
            slot(1),
            slot(2)
        );
    }
    out.push_str("];\n");
    out
}

