//! The generated Rust sources: the four files of `src/unicode/generated`, laid out as `cargo fmt` leaves them.
//!
//! agterm's own: Ghostty writes its tables as Zig (`lut.zig`'s `writeZig`) or keeps them in comptime constants.
//! Arrays of numbers and booleans are packed as rustfmt's mixed layout packs them (as many items to a line as fit in
//! 119 columns, indented by four), struct literals are one field to a line, and the case folding list is
//! `#[rustfmt::skip]`, one entry to a line, so `cargo fmt --check` holds on the output as written.

use std::fmt::Write as _;

use crate::Inputs;
use crate::lut::Tables;
use crate::props::Properties;

/// rustfmt's `max_width` (`rustfmt.toml`).
const MAX_WIDTH: usize = 120;

/// rustfmt's `array_width`, the widest array it keeps on one line: 60% of `max_width` (`use_small_heuristics`).
const ARRAY_WIDTH: usize = MAX_WIDTH * 6 / 10;

/// `name: [ty; len] = [items...];` as rustfmt lays it out: on one line when it fits, else packed lines.
fn array(out: &mut String, decl: &str, ty: &str, items: &[String]) {
    let head = format!("{decl}: [{ty}; {}] = [", items.len());
    let joined = items.join(", ");
    let one_line = format!("{head}{joined}];");
    if joined.len() <= ARRAY_WIDTH && one_line.len() <= MAX_WIDTH {
        out.push_str(&one_line);
        out.push('\n');
        return;
    }
    out.push_str(&head);
    out.push('\n');
    let mut line = String::new();
    for item in items {
        // each line is the indent, the items separated by ", ", and a trailing comma, and stays below the maximum
        // width, as rustfmt packs them
        if !line.is_empty() && line.len() + 2 + item.len() + 1 >= MAX_WIDTH {
            out.push_str(&line);
            out.push_str(",\n");
            line.clear();
        }
        if line.is_empty() {
            line.push_str("    ");
        } else {
            line.push_str(", ");
        }
        line.push_str(item);
    }
    if !line.is_empty() {
        out.push_str(&line);
        out.push_str(",\n");
    }
    out.push_str("];\n");
}

fn numbers<T: ToString>(values: &[T]) -> Vec<String> {
    values.iter().map(ToString::to_string).collect()
}

/// The header naming where a file's tables come from: each paragraph wrapped into doc lines of at most `MAX_WIDTH`
/// columns, the paragraphs apart by an empty doc line, then a blank line.
fn header(out: &mut String, paragraphs: &[String]) {
    for (i, paragraph) in paragraphs.iter().enumerate() {
        if i > 0 {
            out.push_str("//!\n");
        }
        let mut line = String::from("//!");
        for word in paragraph.split_whitespace() {
            if line.len() > "//!".len() && line.len() + 1 + word.len() > MAX_WIDTH {
                out.push_str(&line);
                out.push('\n');
                line = String::from("//!");
            }
            line.push(' ');
            line.push_str(word);
        }
        out.push_str(&line);
        out.push('\n');
    }
    out.push('\n');
}

/// The uucode release and commit, as the headers name them.
fn uucode(inputs: &Inputs) -> String {
    format!("uucode {} @ `{}`", inputs.uucode_version, inputs.uucode_rev_short)
}

/// `props_data.rs`.
pub(crate) fn props_data(inputs: &Inputs, tables: &Tables<Properties>) -> String {
    let mut out = String::new();
    header(
        &mut out,
        &[
            "The per-code-point [`Properties`] table: `stage1`/`stage2`/`stage3` of the three-level lookup \
             ([`crate::unicode::lut`]) that `props_table` reads."
                .to_owned(),
            format!(
                "Generated by `scripts/gen-vt-unicode.sh`: Ghostty's `props-unigen` (`src/unicode/props_uucode.zig` \
                 at `LIBGHOSTTY_VT_REV`) over the fields of {} and `src/build/uucode_config.zig`, from the UCD {} \
                 that uucode ships. The stages are `static`, laid out once, as Zig's container-level constants are. \
                 Do not edit: rerun the script.",
                uucode(inputs),
                inputs.ucd_version
            ),
        ],
    );
    out.push_str("use crate::unicode::props::{GraphemeBreakNoControl, Properties};\n\n");
    array(&mut out, "pub(crate) static STAGE1", "u16", &numbers(&tables.stage1));
    array(&mut out, "pub(crate) static STAGE2", "u16", &numbers(&tables.stage2));
    let _ = writeln!(
        out,
        "pub(crate) static STAGE3: [Properties; {}] = [",
        tables.stage3.len()
    );
    for p in &tables.stage3 {
        let _ = write!(
            out,
            "    Properties {{\n        width: {},\n        width_zero_in_grapheme: {},\n        grapheme_break: \
             GraphemeBreakNoControl::{:?},\n        emoji_vs_base: {},\n    }},\n",
            p.width, p.width_zero_in_grapheme, p.grapheme_break, p.emoji_vs_base
        );
    }
    out.push_str("];\n");
    out
}

