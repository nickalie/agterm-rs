#!/usr/bin/env bash
# Regenerate the checked-in crates/agterm-ghostty-sys/src/bindings.rs from the vendored prefix's ghostty.h.
# Run after a GHOSTTY_REV or ghostty patch change (scripts/build-ghostty.sh first), then review the diff.
# Only the subset of the embedding API agterm uses is bound: the functions below and the types they reach.
# Usage: scripts/gen-ghostty-bindings.sh [HEADER]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HEADER="${1:-$("$ROOT/scripts/build-ghostty.sh" --print-prefix)/include/ghostty.h}"
OUT="$ROOT/crates/agterm-ghostty-sys/src/bindings.rs"
[[ -s "$HEADER" ]] || { echo "no ghostty.h at $HEADER: run scripts/build-ghostty.sh" >&2; exit 1; }
command -v bindgen >/dev/null || { echo "bindgen is required (cargo install bindgen-cli)" >&2; exit 1; }

FUNCTIONS=(
  ghostty_init
  ghostty_config_new ghostty_config_free ghostty_config_clone ghostty_config_load_file
  ghostty_config_load_default_files ghostty_config_load_recursive_files ghostty_config_finalize ghostty_config_get
  ghostty_config_diagnostics_count ghostty_config_get_diagnostic
  ghostty_app_new ghostty_app_free ghostty_app_tick ghostty_app_update_config ghostty_app_set_color_scheme
  ghostty_surface_config_new ghostty_surface_new ghostty_surface_free ghostty_surface_userdata
  ghostty_surface_inherited_config ghostty_surface_update_config ghostty_surface_refresh ghostty_surface_draw
  ghostty_surface_set_content_scale ghostty_surface_set_focus ghostty_surface_set_size ghostty_surface_size
  ghostty_surface_foreground_pid ghostty_surface_set_color_scheme ghostty_surface_key ghostty_surface_text
  ghostty_surface_feed ghostty_surface_preedit ghostty_surface_mouse_button ghostty_surface_mouse_pos
  ghostty_surface_mouse_scroll ghostty_surface_ime_point ghostty_surface_binding_action
  ghostty_surface_complete_clipboard_request ghostty_surface_has_selection ghostty_surface_read_selection
  ghostty_surface_read_text ghostty_surface_free_text
)
# Read through ghostty_config_get's untyped out-pointer, so no function signature reaches them.
TYPES='ghostty_config_(color|color_list|palette)_s'

args=()
for function in "${FUNCTIONS[@]}"; do
  args+=(--allowlist-function "^$function\$")
done

{
  echo "// Generated by scripts/gen-ghostty-bindings.sh from ghostty.h at the GHOSTTY_REV of build/pins.env."
  echo "// Do not edit by hand."
  echo
  bindgen "$HEADER" "${args[@]}" --allowlist-type "^($TYPES)\$" \
    --no-layout-tests --rust-edition 2024 --rust-target 1.85 --no-doc-comments \
    --default-enum-style consts --no-prepend-enum-name -- -I"$(dirname "$HEADER")"
} >"$OUT"
echo "→ wrote $OUT" >&2
