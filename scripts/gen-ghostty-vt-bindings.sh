#!/usr/bin/env bash
# Regenerate the checked-in crates/agterm-ghostty-vt-sys/src/bindings.rs from the vendored prefix's ghostty/vt.h.
# Run after a LIBGHOSTTY_VT_REV or build/patches/ghostty-vt change (scripts/build-ghostty-vt.sh first), then review the
# diff: the vt API is still moving, so a pin bump is a change of its own.
# Only the parts of the C API agterm-ghostty-vt binds are generated: the function families below and the types they
# reach, plus the option, data and callback types their untyped `void*` values carry and the integer `#define`
# constants those values take (bindgen emits no `#define` without an allowlist).
# Usage: scripts/gen-ghostty-vt-bindings.sh [HEADER]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HEADER="${1:-$("$ROOT/scripts/build-ghostty-vt.sh" --print-prefix)/include/ghostty/vt.h}"
OUT="$ROOT/crates/agterm-ghostty-vt-sys/src/bindings.rs"
[[ -s "$HEADER" ]] || { echo "no ghostty/vt.h at $HEADER: run scripts/build-ghostty-vt.sh" >&2; exit 1; }
command -v bindgen >/dev/null || { echo "bindgen is required (cargo install bindgen-cli)" >&2; exit 1; }

# Function families, each a name prefix: the terminal with its options and effects, the render state with its row and
# cell iterators, the key and mouse encoders with their events, selection, formatter, paste, search, kitty graphics,
# the process-global sys hooks and the standalone OSC parser; then the helpers they need: the library allocator (frees
# what *_alloc returns), raw cell/row and grid-ref reads, mode tags and focus reports.
FUNCTIONS=(
  ghostty_terminal_
  ghostty_render_state_
  ghostty_key_encoder_ ghostty_key_event_
  ghostty_mouse_encoder_ ghostty_mouse_event_
  ghostty_selection_
  ghostty_formatter_
  ghostty_paste_
  ghostty_search_
  ghostty_kitty_graphics_
  ghostty_sys_
  ghostty_osc_
  ghostty_alloc ghostty_free
  ghostty_cell_get ghostty_row_get ghostty_grid_ref_ ghostty_tracked_grid_ref_
  ghostty_mode_ ghostty_focus_encode
  ghostty_style_default ghostty_build_info
)
# Type families (`Ghostty<name>...`) reached through untyped `void*` option values and out-pointers, so no function
# signature pulls them in.
TYPES=(
  Terminal RenderState Key Mouse Selection Formatter Paste Search Kitty Sys Osc
  Cell Row GridRef Mode Focus Style Color String Buffer Point BuildInfo Optimize ClipboardRead ClipboardWrite
  OptionAsAlt SurfacePosition Codepoints
)
# `#define` families of those values: key modifiers (GhosttyMods), kitty keyboard flags, device attributes, named
# colors. The function-like ones (GHOSTTY_MODE_*, GHOSTTY_COLOR_PALETTE_MASK_*) cannot be bound and are mirrored by hand.
VARS=(MODS KITTY_KEY DA COLOR_NAMED)

functions="$(IFS='|'; echo "${FUNCTIONS[*]}")"
types="$(IFS='|'; echo "${TYPES[*]}")"
vars="$(IFS='|'; echo "${VARS[*]}")"

{
  echo "// Generated by scripts/gen-ghostty-vt-bindings.sh from ghostty/vt.h at the LIBGHOSTTY_VT_REV of"
  echo "// build/pins.env, build/patches/ghostty-vt applied. Do not edit by hand."
  echo
  bindgen "$HEADER" --allowlist-function "^($functions).*\$" --allowlist-type "^Ghostty($types)[A-Za-z0-9_]*\$" \
    --allowlist-var "^GHOSTTY_($vars)_[A-Z0-9_]*\$" \
    --no-layout-tests --rust-edition 2024 --rust-target 1.85 --no-doc-comments \
    --default-enum-style consts --no-prepend-enum-name -- -I"$(dirname "$(dirname "$HEADER")")" -DGHOSTTY_STATIC
} >"$OUT"
echo "→ wrote $OUT" >&2
